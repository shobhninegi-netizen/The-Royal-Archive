let currentMode = "easy";
let currentQuestions = spiritualityEasyQuestions;

let currentQuestion = 0;
let score = 0;
let answered = false;


// ==========================================
// GET ELEMENTS
// ==========================================

const questionElement = document.querySelector(".question");
const optionButtons = document.querySelectorAll(".option");
const questionNumber = document.querySelector(".question-number");
const answerToast = document.querySelector(".answer-toast");
const explainElement = document.querySelector(".explain");
const nextButton = document.querySelector(".next-btn");


// ==========================================
// LOAD QUESTION
// ==========================================

function loadQuestion() {

    answered = false;

    const current = currentQuestions[currentQuestion];

    questionElement.textContent = current.question;

    questionNumber.textContent =
        `${currentQuestion + 1}/${currentQuestions.length}`;

    explainElement.textContent = "";

    answerToast.textContent = "";
    answerToast.classList.add("hidden");

    optionButtons.forEach((button, index) => {

        button.textContent = current.options[index];

        button.disabled = false;

        button.style.borderColor = "";
        button.style.background = "";
        button.style.color = "";

    });

    nextButton.style.display = "none";
}


// ==========================================
// CHECK ANSWER
// ==========================================

function checkAnswer(selectedButton) {

    if (answered) return;

    answered = true;

    const current = currentQuestions[currentQuestion];
    const selectedAnswer = selectedButton.textContent;

    optionButtons.forEach(button => {
        button.disabled = true;
    });

    if (selectedAnswer === current.answer) {

        score++;

        answerToast.textContent = "✦ Correct — your insight deepens.";
        answerToast.classList.remove("hidden");

        selectedButton.style.borderColor = "#9b8a65";
        selectedButton.style.background = "rgba(126, 151, 112, 0.16)";
        selectedButton.style.color = "#d8dfcf";

    } else {

        answerToast.textContent =
            `✦ Not quite. The correct answer is: ${current.answer}`;

        answerToast.classList.remove("hidden");

        selectedButton.style.borderColor = "#956d67";
        selectedButton.style.background = "rgba(120, 70, 70, 0.14)";

        optionButtons.forEach(button => {

            if (button.textContent === current.answer) {

                button.style.borderColor = "#9b8a65";
                button.style.background = "rgba(126, 151, 112, 0.16)";
                button.style.color = "#d8dfcf";

            }

        });

    }

    explainElement.textContent = current.explanation;

    nextButton.style.display = "inline-block";
}


// ==========================================
// NEXT QUESTION
// ==========================================

function nextQuestion() {

    if (!answered) return;

    currentQuestion++;

    if (currentQuestion >= currentQuestions.length) {

        showResult();

        return;
    }

    loadQuestion();
}


// ==========================================
// RESULT
// ==========================================

function showResult() {

    questionElement.textContent =
        "Your Spiritual Journey Is Complete";

    questionNumber.textContent =
        `${score}/${currentQuestions.length}`;

    optionButtons.forEach(button => {
        button.style.display = "none";
    });

    answerToast.classList.remove("hidden");

    const percentage =
        Math.round((score / currentQuestions.length) * 100);

    if (percentage >= 80) {

        answerToast.textContent =
            `✦ Excellent. ${score}/${currentQuestions.length} — A thoughtful seeker.`;

    } else if (percentage >= 50) {

        answerToast.textContent =
            `✦ ${score}/${currentQuestions.length} — The journey continues.`;

    } else {

        answerToast.textContent =
            `✦ ${score}/${currentQuestions.length} — Every question is a doorway to learning.`;

    }

    explainElement.textContent =
        "Spirituality is not merely about knowing answers — it is about questioning, observing, and understanding.";

    nextButton.textContent = "RESTART ↻";
    nextButton.style.display = "inline-block";

    nextButton.onclick = restartQuiz;
    showQuizComplete();
}


// ==========================================
// RESTART
// ==========================================

function restartQuiz() {

    currentQuestion = 0;
    score = 0;

    optionButtons.forEach(button => {
        button.style.display = "block";
    });

    nextButton.textContent = "NEXT →";

    nextButton.onclick = nextQuestion;

    loadQuestion();
}


// ==========================================
// OPTION EVENTS
// ==========================================

optionButtons.forEach(button => {

    button.addEventListener("click", function () {

        checkAnswer(this);

    });

});


// ==========================================
// NEXT EVENT
// ==========================================

nextButton.addEventListener("click", nextQuestion);


// ==========================================
// MODE SUPPORT
// ==========================================


const savedMode = localStorage.getItem("quizDifficulty");

if (savedMode === "medium") {

    currentMode = "medium";
    currentQuestions = spiritualityMediumQuestions;

} else if (savedMode === "hard") {

    currentMode = "hard";
    currentQuestions = spiritualityHardQuestions;

} else {

    currentMode = "easy";
    currentQuestions = spiritualityEasyQuestions;

}


// ==========================================
// START
// ==========================================

loadQuestion();
